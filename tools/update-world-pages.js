// Rewrites the script block of the 3D world pages (web/world/grade-2.html, grade-5.html) from tools/world-manifest.json.
// Run after adding, renaming or removing a file in web/world, or changing the load order: node tools/update-world-pages.js
const fs = require('node:fs');
const path = require('node:path');

const manifest = require('./world-manifest.json');

const WEB = path.join(__dirname, '..', 'web');
const START = '<!-- world scripts: generated by tools/update-world-pages.js from tools/world-manifest.json -->';
const END = '<!-- end world scripts -->';
const NO_GRADE = ['lang', 'world', 'subjects', 'bosses'];

function block(grade) {
  const tags = manifest.engines.map((name) => '<script src="../engine/' + name + '.js"' + (NO_GRADE.includes(name) ? '' : ' data-grade="' + grade + '"') + '></script>')
    .concat(manifest.vendor.map((f) => '<script src="../' + f + '"></script>'), manifest.world.map((f) => '<script src="' + f + '"></script>'));
  return [START].concat(tags, [END]).join('\n');
}

function update(page, grade) {
  const file = path.join(WEB, 'world', page);
  const html = fs.readFileSync(file, 'utf8');
  const from = html.indexOf(START);
  const to = html.indexOf(END);
  if (from >= 0 && to > from) return fs.writeFileSync(file, html.slice(0, from) + block(grade) + html.slice(to + END.length));
  const first = html.indexOf('<script src="../engine/lang.js">');
  const last = html.indexOf('<script src="world-main.js"></script>') + '<script src="world-main.js"></script>'.length;
  if (first < 0 || last < first) throw new Error(page + ': no script block found');
  fs.writeFileSync(file, html.slice(0, first) + block(grade) + html.slice(last));
}

update('grade-2.html', 'grade2');
update('grade-5.html', 'grade5');
console.log('world pages now load ' + (manifest.engines.length + manifest.vendor.length + manifest.world.length) + ' scripts each');
